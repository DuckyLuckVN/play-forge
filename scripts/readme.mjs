// Regenerates the games section of README.md from games/games.json, with
// GitHub Pages links derived from the `origin` remote. Runs as part of
// `npm run build`; also available as `npm run readme`.
import { execSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const START = '<!-- games:start (generated by scripts/readme.mjs, do not edit) -->'
const END = '<!-- games:end -->'

/** https://<owner>.github.io/<repo>/ for a GitHub remote, else null. */
function pagesUrl() {
  let remote = process.env.GITHUB_REPOSITORY // set in GitHub Actions
  if (!remote) {
    try {
      remote = execSync('git remote get-url origin', { cwd: root, encoding: 'utf8' }).trim()
    } catch {
      return null
    }
  }
  const m = /(?:github\.com[:/])?([^/:]+)\/([^/]+?)(?:\.git)?$/.exec(remote)
  if (!m) return null
  const [, owner, repo] = m
  return repo.toLowerCase() === `${owner.toLowerCase()}.github.io`
    ? `https://${owner.toLowerCase()}.github.io/`
    : `https://${owner.toLowerCase()}.github.io/${repo}/`
}

export function updateReadme() {
  const games = JSON.parse(readFileSync(`${root}/games/games.json`, 'utf8'))
  const base = pagesUrl()
  const link = (path, text) => (base ? `[${text}](${base}${path})` : `\`${path}\``)

  const section = [
    START,
    `**▶ Play now: ${link('', base ?? 'launcher')}**`,
    '',
    '| Game | Players | Description |',
    '| --- | --- | --- |',
    ...games.map(
      (g) => `| ${link(`games/${g.id}/`, g.title)} | ${g.players} | ${g.description} |`,
    ),
    END,
  ].join('\n')

  const path = `${root}/README.md`
  const readme = readFileSync(path, 'utf8')
  const start = readme.indexOf(START)
  const end = readme.indexOf(END)
  if (start < 0 || end < 0) throw new Error(`README.md is missing the ${START} … ${END} markers`)
  const next = readme.slice(0, start) + section + readme.slice(end + END.length)
  if (next !== readme) writeFileSync(path, next)
  return next !== readme
}

if (import.meta.url === `file://${process.argv[1]}`) {
  console.log(updateReadme() ? 'README.md updated' : 'README.md already up to date')
}
